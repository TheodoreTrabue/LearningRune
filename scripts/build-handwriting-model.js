import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { splitSamples } from './handwriting-data.js';
import { normalize } from '../src/recognizer.js';
import { modelMetadata as previous } from '../test/fixtures/handwriting-v1.js';

const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/build-handwriting-model.js path/to/export.json');
const raw = fs.readFileSync(source, 'utf8');
const { development, heldOut, regressionIds, freshHeldOutIds } = splitSamples(JSON.parse(raw), previous);
const metadata = {
  version: 'handwriting-v2',
  sourceSha256: createHash('sha256').update(raw).digest('hex'),
  split: 'Preserve all 26 previous held-out drawings; reserve the last two new drawings per updated letter before development.',
  regressionIds,
  freshHeldOutIds,
  developmentCount: development.length,
  heldOutCount: heldOut.length,
  developmentIds: development.map(s => s.id),
  heldOutIds: heldOut.map(s => s.id)
};
const templates = development.map(sample => ({ letter: sample.letter, points: normalize(sample.strokes).map(p => [Number(p.x.toFixed(5)), Number(p.y.toFixed(5))]) }));
if (templates.some(t => !t.points.length)) throw new Error('Empty development template');
const code = `// Generated by scripts/build-handwriting-model.js. Do not edit by hand.\n// Only development drawings are included. Coordinates are normalized; no timestamps or ink colors.\nexport const modelMetadata = ${JSON.stringify(metadata, null, 2)};\nconst examples = [\n${templates.map(t => JSON.stringify(t)).join(',\n')}\n];\nexport const handwritingTemplates = examples.map(({ letter, points }) => ({ letter, cloud: points.map(([x, y]) => ({ x, y })) }));\n`;
fs.writeFileSync(new URL('../src/handwriting-templates.js', import.meta.url), code);
console.log(`Built ${templates.length} development templates; ${heldOut.length} drawings excluded.`);
